#!/usr/bin/env node
// Generates docs/README.md, the index of every Markdown file under docs/, from each file's first heading.
// `node scripts/docs-index.mjs` rewrites the index; `--check` exits 1 when it is out of date.
import {readdirSync,readFileSync,statSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join,relative,resolve,sep} from 'node:path';

const root=resolve(fileURLToPath(new URL('..',import.meta.url))),docs=join(root,'docs'),INDEX=join(docs,'README.md');

function markdown(directory){return readdirSync(directory).sort().flatMap(name=>{const path=join(directory,name);return statSync(path).isDirectory()?markdown(path):name.endsWith('.md')?[path]:[];});}
const title=path=>{const match=/^# (.+)$/m.exec(readFileSync(path,'utf8').replaceAll('\r\n','\n'));return match?match[1].trim():relative(docs,path);};
const posix=path=>relative(docs,path).split(sep).join('/');
const entry=path=>`- [${title(path)}](${posix(path)})`;

/** Text of the index for the files currently under docs/. */
export function render(){
 const files=markdown(docs).filter(path=>path!==INDEX),under=prefix=>files.filter(path=>posix(path).startsWith(prefix));
 const specs=under('specs/'),decisions=under('adr/'),guides=files.filter(path=>!posix(path).includes('/'));
 return ['# Documentation index','','Generated by `npm run docs` from the first heading of each file; do not edit by hand.','','## Specifications','',...specs.map(entry),'','## Architecture decisions','',...decisions.map(entry),'','## Guides and references','',...guides.map(entry),''].join('\n');
}

if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const expected=render(),current=(()=>{try{return readFileSync(INDEX,'utf8').replaceAll('\r\n','\n');}catch{return '';}})();
 if(process.argv.includes('--check')){if(current!==expected){console.error('docs/README.md is out of date; run npm run docs');process.exitCode=1;}else console.log('docs/README.md is up to date');}
 else{if(current!==expected)writeFileSync(INDEX,expected);console.log(current===expected?'docs/README.md already up to date':'Updated docs/README.md');}
}
